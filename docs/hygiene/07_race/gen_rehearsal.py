# Builds the two rolled-back rehearsals from the real scripts: seed body, the four credits one after the other,
# verify, cleanup body (with its guard). 'trip' leaves one extra coin row behind before the guard, which must refuse.
import pathlib, re
D = pathlib.Path(__file__).parent
body = lambda f: (D / f).read_text().split("-- BODY START\n")[1].split("-- BODY END\n")[0]
credit = lambda f: re.search(r"UPDATE race_out SET j = (public\._credit_checkin\([^;]*\));", (D / f).read_text()).group(1)
snap = (D / "07_snapshot.sql").read_text().rstrip().removesuffix("order by 1")
for case in ("pass", "trip"):
    cleanup = body("07_race_cleanup.sql")
    if case == "trip":
        stray = ("INSERT INTO public.coin_transactions (user_id, amount, transaction_type, description, reference_id)\n"
                 "VALUES ('ae240bb6-e629-401e-9fb6-feb1ed21cee9', 1, 'daily_checkin', 'rehearsal stray row', 'stray');\n")
        cleanup = cleanup.replace("DO $guard$", stray + "DO $guard$", 1)
    sql = (f"-- 07 race rehearsal ({case}), ONE transaction that ends in ROLLBACK. Generated by gen_rehearsal.py.\nBEGIN;\n"
           f"CREATE TEMP TABLE snap0 AS {snap};\n" + body("07_race_seed.sql") +
           "CREATE TEMP TABLE out (k text, v text);\n" +
           "".join(f"INSERT INTO out SELECT '{f}', {credit(f)}::text;\n" for f in ("07_race1_A.sql", "07_race1_B.sql", "07_cap_A.sql", "07_cap_B.sql")) +
           "CREATE TEMP TABLE verify AS " + (D / "07_race_verify.sql").read_text().split("\n", 2)[2] +
           cleanup +
           f"CREATE TEMP TABLE snap1 AS {snap};\n"
           "DO $r$ BEGIN RAISE EXCEPTION E'REHEARSAL_RESULTS\\n%\\nverify %\\nguard passed; economy hashes equal to before the seed: %\\n%',\n"
           "  (SELECT string_agg(k || ' ' || v, E'\\n' ORDER BY k) FROM out), (SELECT row_to_json(verify)::text FROM verify),\n"
           "  NOT EXISTS (SELECT * FROM snap0 EXCEPT SELECT * FROM snap1) AND NOT EXISTS (SELECT * FROM snap1 EXCEPT SELECT * FROM snap0),\n"
           "  (SELECT string_agg(t || ' ' || n || ' ' || h, E'\\n' ORDER BY t) FROM snap1); END $r$;\nROLLBACK;\n")
    (D / f"07_rehearsal_{case}.sql").write_text(sql)
print("ok")
